void UImmortalIconWidget::NativeOnInitialized()
{
	Super::NativeOnInitialized();
	USizeBox* Size = WidgetTree->ConstructWidget<USizeBox>();
	Size->SetWidthOverride(64.0f);
	Size->SetHeightOverride(64.0f);
	WidgetTree->RootWidget = Size;
	SetVisibility(ESlateVisibility::HitTestInvisible);
}

int32 UImmortalIconWidget::NativePaint(const FPaintArgs& Args, const FGeometry& Geometry,
	const FSlateRect& CullingRect, FSlateWindowElementList& Out, int32 Layer,
	const FWidgetStyle& Style, bool bEnabled) const
{
	const int32 Base = Super::NativePaint(Args, Geometry, CullingRect, Out, Layer, Style, bEnabled);
	const float Unit = FMath::Min(Geometry.GetLocalSize().X, Geometry.GetLocalSize().Y) / 18.0f;
	const FVector2D Origin = (Geometry.GetLocalSize() - FVector2D(Unit * 16.0f)) * 0.5f;
	const FSlateBrush* Brush = FCoreStyle::Get().GetBrush("WhiteBrush");
	auto Filled = [this](int32 X, int32 Y) { return X >= 0 && X < 16 && Y >= 0 && Y < 16
		&& (Symbols[IconIndex][Y] & (1u << (15-X))) != 0; };
	for (int32 Y = -1; Y <= 16; ++Y)
	for (int32 X = -1; X <= 16; ++X)
	{
		const bool bFill = Filled(X,Y);
		if (!bFill && !Filled(X-1,Y) && !Filled(X+1,Y) && !Filled(X,Y-1) && !Filled(X,Y+1)) continue;
		const bool bJade = IconIndex == 0 || IconIndex == 1 || IconIndex == 11 || IconIndex == 19;
		FLinearColor Color = bFill ? (bJade ? FLinearColor(0.36f,0.78f,0.56f) : FLinearColor(0.92f,0.66f,0.30f))
			: FLinearColor(0.055f,0.055f,0.09f);
		if (bFill && !Filled(X,Y-1)) Color = bJade ? FLinearColor(0.76f,0.97f,0.73f) : FLinearColor(1.0f,0.9f,0.60f);
		if (bFill && !Filled(X,Y+1)) Color *= 0.7f;
		Color.A = bEnabled ? 1.0f : 0.45f;
		FSlateDrawElement::MakeBox(Out, Base+1, Geometry.ToPaintGeometry(FVector2D(Unit),
			FSlateLayoutTransform(Origin + FVector2D(X*Unit,Y*Unit))), Brush,
			ESlateDrawEffect::None, Color * Style.GetColorAndOpacityTint());
	}
	return Base+1;
}
